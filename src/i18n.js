/** Chuyển ngữ VI/EN cho toàn bộ giao diện.
 *
 * Toàn bộ code còn lại vẫn viết chuỗi tiếng Việt trực tiếp như trước (không đổi sang khoá kiểu
 * "nav.home") — t() nhận THẲNG chuỗi tiếng Việt gốc làm khoá tra từ điển EN bên dưới. Cách này cho
 * phép bọc dần từng chuỗi bằng t('...') mà không phải bơm hàng nghìn khoá nhân tạo vào 20 file view.
 * Thiếu bản dịch (khoá lạ, hoặc đang ở giao diện VI) thì luôn rơi về đúng chuỗi tiếng Việt gốc — an
 * toàn tuyệt đối, không bao giờ hiện "undefined" hay khoá thô ngoài giao diện.
 */
const LANG_KEY = 'nv.lang';

export function getLang() {
  try { return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'vi'; } catch (e) { return 'vi'; }
}
export const isEn = () => getLang() === 'en';

/** Đổi ngôn ngữ + phát sự kiện cho app.js vẽ lại toàn bộ giao diện đang mở. */
export function setLang(lang) {
  const l = lang === 'en' ? 'en' : 'vi';
  if (l === getLang()) return;
  try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* chế độ ẩn danh: chỉ đổi được trong phiên hiện tại */ }
  try { document.documentElement.lang = l === 'en' ? 'en' : 'vi'; } catch (e) { /* không có DOM (test) */ }
  window.dispatchEvent(new CustomEvent('nv:lang-changed', { detail: { lang: l } }));
}
export const toggleLang = () => setLang(isEn() ? 'vi' : 'en');

/** t(vi) — trả về bản dịch EN nếu đang ở giao diện tiếng Anh và có trong từ điển, ngược lại trả
 * nguyên chuỗi tiếng Việt truyền vào (đây chính là hành vi mặc định khi đang ở giao diện VI). */
export function t(vi) {
  if (vi == null || vi === '') return vi;
  if (!isEn()) return vi;
  const hit = EN[vi];
  return hit == null ? vi : hit;
}

/** Biến thể có tham số, cho các câu ghép số/động (vd "3 ngày trước"). `viBuild` dựng câu tiếng Việt
 * như cũ; `enBuild` (khi có) dựng câu tiếng Anh tương ứng — dùng khi không thể tra thẳng theo từ
 * điển vì phần số thay đổi liên tục. */
export function tf(viBuild, enBuild) {
  return isEn() && enBuild ? enBuild() : viBuild();
}

