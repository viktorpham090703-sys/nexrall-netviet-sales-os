/** Bỏ dấu tiếng Việt: "Nguyễn Văn Hậu" → "Nguyen Van Hau". */
export const stripVi = (s) => String(s).normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/đ/g, 'd').replace(/Đ/g, 'D');

/** Tên người (tài khoản nhân sự) — giao diện EN viết không dấu như cách viết tên người Việt trong
 * văn bản tiếng Anh. Chỉ đổi lúc HIỂN THỊ; ô nhập/biểu mẫu vẫn giữ nguyên tên gốc trong CSDL. */
export const personName = (n) => (n && isEn() ? stripVi(n) : n);

/** Chức danh do Admin tự đặt (nv_users.title) là chữ tự do. Giao diện EN: tra từ điển chức danh
 * (không phân biệt hoa thường); chức danh lạ còn tiếng Việt thì rơi về nhãn vai trò tiếng Anh
 * (`fallback`) — không bao giờ để lọt chữ tiếng Việt ra giao diện EN. */
export function jobTitle(title, fallback) {
  const s = String(title == null ? '' : title).trim();
  if (!s || !isEn()) return s;
  const hit = EN[s] || JOB_TITLE_EN[s.toLowerCase()];
  if (hit) return hit;
  return VI_CHARS.test(s) && fallback ? fallback() : s;
}
